"""Turn Shift Pattern Assignments into standard Shift Assignment records."""

from collections import defaultdict

import frappe
from frappe import _
from frappe.utils import add_days, cint, date_diff, getdate, now_datetime, today
from frappe.utils.nestedset import get_descendants_of
from hrms.hr.doctype.shift_assignment.shift_assignment import has_overlapping_timings

from raysut_cement.raysut_cement.scheduling.pattern import rows_by_slot, timetables_for_date
from raysut_cement.raysut_cement.settings import is_enabled

GROUP_FIELDS = {"Department": "department", "Branch": "branch", "Designation": "designation"}


# ---------------------------------------------------------------- employees


def resolve_employees(assignment):
	"""Active employees covered by the assignment (department includes its sub-departments)."""
	filters = {"status": "Active", "company": assignment.company}
	if assignment.assign_to == "Employee":
		filters["name"] = assignment.employee
	elif assignment.assign_to == "Employee Group":
		members = frappe.get_all(
			"Employee Group Table", filters={"parent": assignment.employee_group, "parenttype": "Employee Group"}, pluck="employee"
		)
		filters["name"] = ("in", members or [""])
	elif assignment.assign_to == "Department":
		filters["department"] = ("in", [assignment.department, *get_descendants_of("Department", assignment.department)])
	else:
		field = GROUP_FIELDS[assignment.assign_to]
		filters[field] = assignment.get(field)

	return frappe.get_all(
		"Employee", filters=filters, fields=["name", "employee_name", "date_of_joining", "relieving_date", "default_shift"], order_by="name"
	)


# ---------------------------------------------------------------- generation


def generate(assignment, from_date=None):
	"""Create or extend Shift Assignments from `from_date` (default today) up to the horizon."""
	if assignment.docstatus != 1 or assignment.status != "Active":
		return

	pattern = frappe.get_doc("Shift Pattern", assignment.shift_pattern)
	slots = rows_by_slot(pattern)
	start = max(getdate(assignment.start_date), getdate(from_date or today()))
	end = add_days(today(), cint(assignment.generation_horizon_days) or 60)
	if assignment.end_date:
		end = min(getdate(end), getdate(assignment.end_date))
	end = getdate(end)

	employees = resolve_employees(assignment)
	allow_multiple = cint(frappe.db.get_single_value("HR Settings", "allow_multiple_shift_assignments"))
	log = []

	for emp in employees:
		emp_start = max(start, getdate(emp.date_of_joining)) if emp.date_of_joining else start
		emp_end = min(end, getdate(emp.relieving_date)) if emp.relieving_date else end
		if emp_start > emp_end:
			continue
		if conflict := other_pattern_assignment(assignment, emp.name, emp_start, emp_end):
			log.append((emp.name, emp_start, _("Already scheduled by {0}").format(conflict)))
			continue

		own = existing_assignments(emp.name, emp_start, emp_end, assignment.name)
		manual = existing_assignments(emp.name, emp_start, emp_end, None)
		wanted = defaultdict(list)  # timetable -> dates
		for offset in range(date_diff(emp_end, emp_start) + 1):
			date = add_days(emp_start, offset)
			for timetable in timetables_for_date(pattern, assignment.start_date, date, slots):
				if any(covers(sa, date, timetable) for sa in own):
					continue
				blocking = [m for m in manual if covers(m, date) and (not allow_multiple or has_overlapping_timings(m.shift_type, timetable))]
				if blocking:
					log.append((emp.name, date, _("Manual Shift Assignment {0} on this date").format(blocking[0].name)))
					continue
				wanted[timetable].append(getdate(date))

		for timetable, dates in wanted.items():
			for run_start, run_end in merge_consecutive(dates):
				error = create_or_extend(assignment, emp.name, timetable, run_start, run_end, own)
				if error:
					log.append((emp.name, run_start, error))

	record_run(assignment, employees, log)


def merge_consecutive(dates):
	runs = []
	for date in sorted(dates):
		if runs and date_diff(date, runs[-1][1]) == 1:
			runs[-1][1] = date
		else:
			runs.append([date, date])
	return [tuple(r) for r in runs]


def existing_assignments(employee, start, end, pattern_assignment):
	"""Active submitted Shift Assignments touching [start, end]; generated by `pattern_assignment`,
	or manual ones (not generated by any pattern) when it is None."""
	sa = frappe.qb.DocType("Shift Assignment")
	query = (
		frappe.qb.from_(sa)
		.select(sa.name, sa.shift_type, sa.start_date, sa.end_date)
		.where(
			(sa.employee == employee)
			& (sa.docstatus == 1)
			& (sa.status == "Active")
			& (sa.start_date <= end)
			& ((sa.end_date >= add_days(start, -1)) | sa.end_date.isnull())
		)
	)
	if pattern_assignment:
		query = query.where(sa.shift_pattern_assignment == pattern_assignment)
	else:
		query = query.where(sa.shift_pattern_assignment.isnull() | (sa.shift_pattern_assignment == ""))
	return query.run(as_dict=True)


def covers(sa, date, timetable=None):
	date = getdate(date)
	return (
		(timetable is None or sa.shift_type == timetable)
		and getdate(sa.start_date) <= date
		and (not sa.end_date or date <= getdate(sa.end_date))
	)


def create_or_extend(assignment, employee, timetable, start, end, own):
	"""Extend a generated assignment that ends the day before `start`, otherwise create one."""
	frappe.db.savepoint("shift_pattern_generation")
	try:
		previous = next(
			(sa for sa in own if sa.shift_type == timetable and sa.end_date and date_diff(start, sa.end_date) == 1), None
		)
		if previous:
			doc = frappe.get_doc("Shift Assignment", previous.name)
			doc.end_date = end
			doc.save(ignore_permissions=True)
			previous.end_date = end
			return None

		doc = frappe.get_doc(
			{
				"doctype": "Shift Assignment",
				"employee": employee,
				"shift_type": timetable,
				"company": assignment.company,
				"start_date": start,
				"end_date": end,
				"status": "Active",
				"shift_pattern_assignment": assignment.name,
			}
		)
		doc.insert(ignore_permissions=True)
		doc.submit()
		own.append(frappe._dict(name=doc.name, shift_type=timetable, start_date=start, end_date=end))
	except frappe.ValidationError as e:
		frappe.db.rollback(save_point="shift_pattern_generation")
		frappe.clear_last_message()
		return str(e) or _("Could not create Shift Assignment")


def other_pattern_assignment(assignment, employee, start, end):
	"""Another active, submitted pattern assignment that already generated shifts for this employee in the period."""
	sa = frappe.qb.DocType("Shift Assignment")
	rows = (
		frappe.qb.from_(sa)
		.select(sa.shift_pattern_assignment)
		.where(
			(sa.employee == employee)
			& (sa.docstatus == 1)
			& (sa.status == "Active")
			& sa.shift_pattern_assignment.isnotnull()
			& (sa.shift_pattern_assignment != assignment.name)
			& (sa.start_date <= end)
			& ((sa.end_date >= start) | sa.end_date.isnull())
		)
		.limit(1)
	).run(pluck=True)
	return rows[0] if rows else None


def record_run(assignment, employees, log):
	"""Store the resolved employees, new log lines and run time.

	Written directly to the database: this also runs inside the assignment's own
	on_submit, where saving the parent again is not possible."""
	parent = {"parent": assignment.name, "parenttype": "Shift Pattern Assignment"}

	frappe.db.delete("Shift Pattern Assignment Employee", parent)
	assignment.set("employees", [])
	for e in employees:
		assignment.append("employees", {"employee": e.name, "employee_name": e.employee_name}).db_insert()

	seen = {(r.employee, str(r.date), r.reason) for r in assignment.generation_log}
	for employee, date, reason in log:
		if (employee, str(getdate(date)), reason) in seen:
			continue
		seen.add((employee, str(getdate(date)), reason))
		assignment.append("generation_log", {"employee": employee, "date": date, "reason": reason}).db_insert()

	assignment.last_generated_on = now_datetime()
	assignment.db_set("last_generated_on", assignment.last_generated_on, update_modified=False)


# ---------------------------------------------------------------- removal


def clear_future(assignment, employees=None, after=None):
	"""Remove generated shifts after `after` (default today). Past and today's shifts stay;
	an assignment running past `after` is cut back to end on `after`."""
	after = getdate(after or today())
	filters = {"shift_pattern_assignment": assignment.name, "docstatus": 1}
	if employees is not None:
		filters["employee"] = ("in", employees or [""])

	for sa in frappe.get_all("Shift Assignment", filters=filters, fields=["name", "start_date", "end_date"]):
		doc = frappe.get_doc("Shift Assignment", sa.name)
		if getdate(sa.start_date) > after:
			doc.cancel()
			frappe.delete_doc("Shift Assignment", doc.name, ignore_permissions=True, force=True)
		elif not sa.end_date or getdate(sa.end_date) > after:
			doc.end_date = after
			doc.save(ignore_permissions=True)


def regenerate(assignment):
	clear_future(assignment)
	generate(assignment, from_date=add_days(today(), 1))


def regenerate_for_pattern(pattern_name):
	for name in frappe.get_all(
		"Shift Pattern Assignment", filters={"shift_pattern": pattern_name, "docstatus": 1, "status": "Active"}, pluck="name"
	):
		regenerate(frappe.get_doc("Shift Pattern Assignment", name))


# ---------------------------------------------------------------- scheduler


def daily_generation():
	"""Extend every active schedule to its horizon and follow joiners, leavers and transfers."""
	if not is_enabled("enable_shift_scheduling"):
		return
	for name in frappe.get_all("Shift Pattern Assignment", filters={"docstatus": 1, "status": "Active"}, pluck="name"):
		try:
			assignment = frappe.get_doc("Shift Pattern Assignment", name)
			current = {e.name: e for e in resolve_employees(assignment)}
			generated_for = set(
				frappe.get_all("Shift Assignment", filters={"shift_pattern_assignment": name, "docstatus": 1}, pluck="employee")
			)
			# employees who left the group: drop their future shifts
			if gone := sorted(generated_for - set(current)):
				clear_future(assignment, gone)
			# relieved employees: nothing after the relieving date
			for emp in current.values():
				if emp.relieving_date:
					clear_future(assignment, [emp.name], after=emp.relieving_date)
			generate(assignment)
			frappe.db.commit()
		except Exception:
			frappe.db.rollback()
			frappe.log_error(title=f"Shift Pattern generation failed - {name}")
